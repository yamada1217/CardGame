const norm = (s) => String(s).normalize('NFKC').replace(/[\s・=･]/g, '');
let byName = null;
function idOf(key) {
  if (CARDS[key]) return key;
  if (!byName) {
    byName = new Map();
    for (const c of Object.values(CARDS)) if (!byName.has(norm(c.name))) byName.set(norm(c.name), c.id);
  }
  return byName.get(norm(key)) || null;
}

// { カード名: 枚数 } を { カードID: 枚数 } にする。見つからない名前は missing に入れる
export function resolveDeck(deck) {
  const cards = {}, missing = [];
  for (const [key, n] of Object.entries(deck.cards)) {
    const id = idOf(key);
    if (!id) { missing.push(key); continue; }
    cards[id] = (cards[id] || 0) + n;
  }
  return { cards, missing };
}
